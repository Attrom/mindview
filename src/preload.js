const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('desktop', {
  listProjects: () => ipcRenderer.sendSync('projects:list'),
  load: id => ipcRenderer.sendSync('project:load', id),
  save: (id, text) => ipcRenderer.invoke('project:save', id, text),
  saveSync: (id, text) => ipcRenderer.sendSync('project:saveSync', id, text),
  createProject: name => ipcRenderer.sendSync('project:create', name),
  deleteProject: id => ipcRenderer.sendSync('project:delete', id),
  getSettings: () => ipcRenderer.sendSync('settings:get'),
  setSettings: patch => ipcRenderer.send('settings:set', patch),
  dataPath: () => ipcRenderer.sendSync('data:path'),
  setTheme: name => ipcRenderer.send('theme:set', name),
  setTitle: title => ipcRenderer.send('title:set', title),
  toggleDevTools: () => ipcRenderer.send('dev:tools'),
  saveImage: (bytes, ext) => ipcRenderer.invoke('image:save', bytes, ext),
  pickImages: () => ipcRenderer.invoke('image:pick'),
  imageBase: () => ipcRenderer.sendSync('image:base'),
  share: (method, ...args) => ipcRenderer.invoke('share:call', method, ...args),
  modsList: () => ipcRenderer.sendSync('mods:list'),
  modRead: id => ipcRenderer.sendSync('mods:read', id),
  modsInProject: pid => ipcRenderer.sendSync('mods:inProject', pid),
  modsAdd: () => ipcRenderer.invoke('mods:add'),
  modAddFromProject: (pid, id) => ipcRenderer.invoke('mods:addFromProject', pid, id),
  modRemove: id => ipcRenderer.invoke('mods:remove', id),
  modsOpenFolder: () => ipcRenderer.invoke('mods:openFolder'),
  modsCatalog: () => ipcRenderer.invoke('mods:catalog'),
  modInstall: id => ipcRenderer.invoke('mods:install', id),
  aiAsk: req => ipcRenderer.invoke('ai:ask', req),
  aiAgents: () => ipcRenderer.invoke('ai:agents'),
  aiPick: (id, locate) => ipcRenderer.invoke('ai:pick', id, locate),
  mcpStatus: () => ipcRenderer.invoke('mcp:status'),
  mcpInstall: id => ipcRenderer.invoke('mcp:install', id),
  mcpRemove: id => ipcRenderer.invoke('mcp:remove', id),
});
